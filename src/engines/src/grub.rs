//! GRUB2 Boot Engine module for BootForge.
//! Generates rich GRUB2 configurations, themes, loopback mounts, and boot menu items.

use bootforge_core::types::IsoAnalysis;

/// Configuration options for the GRUB2 bootloader.
#[derive(Debug, Clone)]
pub struct GrubConfigOptions {
    pub timeout: u32,
    pub default_entry: u32,
    pub enable_gfxterm: bool,
    pub theme_path: Option<String>,
    pub custom_resolution: Option<String>,
}

impl Default for GrubConfigOptions {
    fn default() -> Self {
        Self {
            timeout: 10,
            default_entry: 0,
            enable_gfxterm: true,
            theme_path: Some("/bootforge/themes/default/theme.txt".to_string()),
            custom_resolution: Some("auto".to_string()),
        }
    }
}

/// Generate a full grub.cfg script given custom options and a list of ISO entries.
pub fn build_grub_config(options: &GrubConfigOptions, isos: &[IsoAnalysis]) -> String {
    let mut out = String::new();

    out.push_str("# ========================================================\n");
    out.push_str("# Botdigit BootForge Universal Multi-Boot GRUB2 Config\n");
    out.push_str("# Auto-generated by Botdigit BootForge Engine\n");
    out.push_str("# ========================================================\n\n");

    out.push_str(&format!("set timeout={}\n", options.timeout));
    out.push_str(&format!("set default={}\n\n", options.default_entry));

    // Filesystem and Partition drivers
    out.push_str("insmod part_gpt\n");
    out.push_str("insmod part_msdos\n");
    out.push_str("insmod fat\n");
    out.push_str("insmod exfat\n");
    out.push_str("insmod ntfs\n");
    out.push_str("insmod ext2\n");
    out.push_str("insmod iso9660\n");
    out.push_str("insmod udf\n");
    out.push_str("insmod loopback\n");
    out.push_str("insmod chain\n");
    out.push_str("insmod font\n\n");

    if options.enable_gfxterm {
        out.push_str("insmod all_video\n");
        out.push_str("insmod gfxterm\n");
        out.push_str("insmod png\n");
        out.push_str("insmod jpeg\n");
        out.push_str(&format!("set gfxmode={}\n", options.custom_resolution.as_deref().unwrap_or("auto")));
        out.push_str("terminal_output gfxterm\n\n");
    }

    if let Some(ref theme) = options.theme_path {
        out.push_str(&format!("if [ -f {} ]; then\n", theme));
        out.push_str(&format!("    set theme={}\n", theme));
        out.push_str("fi\n\n");
    }

    out.push_str("# Locate BotForge volume by partition label\n");
    out.push_str("search --no-floppy --set=root --label BOOTFORGE\n\n");

    // Group items into categories
    let mut windows_entries = Vec::new();
    let mut linux_entries = Vec::new();
    let mut rescue_entries = Vec::new();
    let mut generic_entries = Vec::new();

    for iso in isos {
        match iso.os_info.family {
            bootforge_core::types::OsFamily::Windows => windows_entries.push(iso),
            bootforge_core::types::OsFamily::Linux => linux_entries.push(iso),
            bootforge_core::types::OsFamily::Recovery | bootforge_core::types::OsFamily::Utility => {
                rescue_entries.push(iso)
            }
            _ => generic_entries.push(iso),
        }
    }

    if !windows_entries.is_empty() {
        out.push_str("submenu \"🪟 Windows Installers & PE ->\" --class windows {\n");
        for iso in &windows_entries {
            out.push_str(&crate::config_gen::generate_grub_entry(iso));
        }
        out.push_str("}\n\n");
    }

    if !linux_entries.is_empty() {
        out.push_str("submenu \"🐧 Linux Distributions ->\" --class linux {\n");
        for iso in &linux_entries {
            out.push_str(&crate::config_gen::generate_grub_entry(iso));
        }
        out.push_str("}\n\n");
    }

    if !rescue_entries.is_empty() {
        out.push_str("submenu \"🛠️ Recovery & Diagnostics Suite ->\" --class rescue {\n");
        for iso in &rescue_entries {
            out.push_str(&crate::config_gen::generate_grub_entry(iso));
        }
        out.push_str("}\n\n");
    }

    for iso in generic_entries {
        out.push_str(&crate::config_gen::generate_grub_entry(iso));
        out.push('\n');
    }

    out.push_str("menuentry \"🔄 Reboot System\" --class reboot {\n");
    out.push_str("    reboot\n");
    out.push_str("}\n\n");

    out.push_str("menuentry \"⏻ Shutdown System\" --class shutdown {\n");
    out.push_str("    halt\n");
    out.push_str("}\n");

    out
}
