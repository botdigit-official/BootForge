//! GRUB2 and UEFI configuration generator.

use bootforge_core::types::{IsoAnalysis, OsFamily};

/// Generate a complete `grub.cfg` file contents for a set of ISOs.
pub fn generate_grub_cfg(isos: &[IsoAnalysis], timeout_seconds: u32) -> String {
    let mut out = String::new();

    out.push_str("# BootForge Universal Boot Drive Configuration\n");
    out.push_str("# Auto-generated by BootForge\n\n");
    out.push_str(&format!("set timeout={}\n", timeout_seconds));
    out.push_str("set default=0\n\n");
    out.push_str("insmod part_gpt\n");
    out.push_str("insmod part_msdos\n");
    out.push_str("insmod fat\n");
    out.push_str("insmod exfat\n");
    out.push_str("insmod ntfs\n");
    out.push_str("insmod ext2\n");
    out.push_str("insmod all_video\n");
    out.push_str("insmod gfxterm\n\n");

    out.push_str("# Theme settings\n");
    out.push_str("if [ -f /bootforge/themes/default/theme.txt ]; then\n");
    out.push_str("    set theme=/bootforge/themes/default/theme.txt\n");
    out.push_str("fi\n\n");

    out.push_str("search --no-floppy --set=root --label BOOTFORGE\n\n");

    for iso in isos {
        out.push_str(&generate_grub_entry(iso));
        out.push('\n');
    }

    out.push_str("menuentry \"Reboot System\" --class reboot {\n");
    out.push_str("    reboot\n");
    out.push_str("}\n\n");

    out.push_str("menuentry \"Shutdown System\" --class shutdown {\n");
    out.push_str("    halt\n");
    out.push_str("}\n");

    out
}

/// Generate an individual GRUB menu entry for an analyzed ISO.
pub fn generate_grub_entry(iso: &IsoAnalysis) -> String {
    let file_name = &iso.file_name;
    let label = &iso.os_info.display_name;

    match iso.os_info.family {
        OsFamily::Windows => {
            format!(
                r#"menuentry "{label}" --class windows {{
    set iso_path="/images/windows/{file_name}"
    loopback loop $iso_path
    chainloader (loop)/efi/boot/bootx64.efi
}}
"#
            )
        }
        OsFamily::Linux => {
            let category_dir = "linux";
            let distro = iso.os_info.distribution.as_deref().unwrap_or("linux").to_lowercase();

            if distro.contains("ubuntu") || distro.contains("mint") {
                format!(
                    r#"menuentry "{label}" --class {distro} --class linux {{
    set iso_path="/images/{category_dir}/{file_name}"
    loopback loop $iso_path
    linux (loop)/casper/vmlinuz boot=casper iso-scan/filename=$iso_path quiet splash ---
    initrd (loop)/casper/initrd
}}
"#
                )
            } else if distro.contains("fedora") {
                format!(
                    r#"menuentry "{label}" --class fedora --class linux {{
    set iso_path="/images/{category_dir}/{file_name}"
    loopback loop $iso_path
    linux (loop)/images/pxeboot/vmlinuz root=live:CDLABEL={label} iso-scan/filename=$iso_path rd.live.image quiet
    initrd (loop)/images/pxeboot/initrd.img
}}
"#
                )
            } else {
                format!(
                    r#"menuentry "{label}" --class linux {{
    set iso_path="/images/{category_dir}/{file_name}"
    loopback loop $iso_path
    linux (loop)/boot/vmlinuz iso-scan/filename=$iso_path quiet
    initrd (loop)/boot/initrd
}}
"#
                )
            }
        }
        OsFamily::Recovery | OsFamily::Utility => {
            format!(
                r#"menuentry "{label}" --class rescue --class utility {{
    set iso_path="/images/rescue/{file_name}"
    loopback loop $iso_path
    linux (loop)/live/vmlinuz boot=live findiso=$iso_path quiet
    initrd (loop)/live/initrd.img
}}
"#
            )
        }
        _ => {
            format!(
                r#"menuentry "{label}" --class generic {{
    set iso_path="/images/{file_name}"
    loopback loop $iso_path
    chainloader (loop)/efi/boot/bootx64.efi
}}
"#
            )
        }
    }
}
